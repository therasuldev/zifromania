import 'package:flutter/material.dart';

class ParticleData {
  final double angle;
  final double distance;
  final double scale;
  final double delay;
  final bool isStarType;
  final Color color;
  final double size;

  ParticleData({
    required this.angle,
    required this.distance,
    required this.scale,
    required this.delay,
    required this.isStarType,
    required this.color,
    required this.size,
  });
}
